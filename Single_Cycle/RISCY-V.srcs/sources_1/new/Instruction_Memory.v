module Instruction_Memory (
    input  wire [31:0] Address,
    output wire [31:0] RD
);

    localparam BASE_ADDRESS = 32'h0000_8000;
    localparam DEPTH        = 16384;

    reg [31:0] memory [0:DEPTH-1];

    wire [31:0] word_index;
    integer i;

    assign word_index = (Address - BASE_ADDRESS) >> 2;

    /*
     * Nếu địa chỉ nằm ngoài vùng Instruction Memory,
     * trả về NOP: addi x0, x0, 0
     */
    assign RD = ((Address >= BASE_ADDRESS) &&
                 (word_index < DEPTH))
              ? memory[word_index]
              : 32'h0000_0013;

    initial begin

        // =====================================================
        // Khởi tạo toàn bộ Instruction Memory bằng NOP
        // =====================================================
        for (i = 0; i < DEPTH; i = i + 1)
            memory[i] = 32'h0000_0013;


        // =====================================================
        // TEST PROGRAM
        //
        // Chương trình bắt đầu tại 0x0000_8000
        //
        // Test:
        //   1. I-type
        //   2. R-type
        //   3. Forwarding từ M
        //   4. Forwarding từ W
        //   5. SW / LW
        //   6. Load-use stall
        //   7. BEQ flush
        //   8. JAL flush
        // =====================================================


        // -----------------------------------------------------
        // 0x0000_8000
        // addi x1, x0, 5
        //
        // x1 = 5
        // -----------------------------------------------------
        memory[0] = 32'h0050_0093;


        // -----------------------------------------------------
        // 0x0000_8004
        // addi x2, x0, 3
        //
        // x2 = 3
        // -----------------------------------------------------
        memory[1] = 32'h0030_0113;


        // -----------------------------------------------------
        // 0x0000_8008
        // add x3, x1, x2
        //
        // x3 = 5 + 3 = 8
        //
        // Đây là bài test forwarding rất quan trọng.
        //
        // Khi add ở Execute:
        //
        // x2 có thể đang ở Memory stage
        // x1 có thể đang ở Writeback stage
        //
        // => ForwardAE / ForwardBE phải hoạt động
        // -----------------------------------------------------
        memory[2] = 32'h0020_81B3;


        // -----------------------------------------------------
        // 0x0000_800C
        // sub x4, x3, x2
        //
        // x4 = 8 - 3 = 5
        //
        // x3 vừa được tạo bởi lệnh trước
        // => test forwarding từ Memory stage
        // -----------------------------------------------------
        memory[3] = 32'h4021_8233;


        // -----------------------------------------------------
        // 0x0000_8010
        // and x5, x3, x1
        //
        // 8 AND 5
        // 1000
        // 0101
        // ----
        // 0000
        //
        // x5 = 0
        // -----------------------------------------------------
        memory[4] = 32'h0011_F2B3;


        // -----------------------------------------------------
        // 0x0000_8014
        // or x6, x1, x2
        //
        // 5 OR 3 = 7
        //
        // x6 = 7
        // -----------------------------------------------------
        memory[5] = 32'h0020_E333;


        // -----------------------------------------------------
        // 0x0000_8018
        // slt x7, x2, x1
        //
        // 3 < 5
        //
        // x7 = 1
        // -----------------------------------------------------
        memory[6] = 32'h0011_23B3;


        // =====================================================
        // MEMORY TEST
        // =====================================================

        // -----------------------------------------------------
        // 0x0000_801C
        // addi x8, x0, 16
        //
        // x8 = 0x00000010
        //
        // Địa chỉ Data Memory = 0x10
        // -----------------------------------------------------
        memory[7] = 32'h0100_0413;


        // -----------------------------------------------------
        // 0x0000_8020
        // sw x3, 0(x8)
        //
        // Memory[0x10] = x3 = 8
        //
        // Nếu Data Memory dùng:
        //
        // word_index = Address[9:2]
        //
        // thì:
        //
        // 0x10 >> 2 = 4
        //
        // => memory[4] = 8
        //
        // x8 vừa được tạo ở instruction trước,
        // nên đây cũng test forwarding cho rs1.
        // -----------------------------------------------------
        memory[8] = 32'h0034_2023;


        // -----------------------------------------------------
        // 0x0000_8024
        // lw x9, 0(x8)
        //
        // x9 = Memory[0x10] = 8
        // -----------------------------------------------------
        memory[9] = 32'h0004_2483;


        // =====================================================
        // LOAD-USE HAZARD TEST
        // =====================================================

        // -----------------------------------------------------
        // 0x0000_8028
        // add x13, x9, x1
        //
        // x9 vừa được load bởi instruction ngay trước.
        //
        // lw x9, ...
        // add x13, x9, x1
        //
        // Đây chính là LOAD-USE HAZARD.
        //
        // Hazard Unit phải tạo:
        //
        // StallF = 1
        // StallD = 1
        // FlushE = 1
        //
        // trong 1 cycle.
        //
        // Sau đó:
        //
        // x13 = 8 + 5 = 13
        // -----------------------------------------------------
        memory[10] = 32'h0014_86B3;


        // =====================================================
        // BEQ TEST
        // =====================================================

        // -----------------------------------------------------
        // 0x0000_802C
        // beq x9, x3, +8
        //
        // x9 = 8
        // x3 = 8
        //
        // => branch TAKEN
        //
        // PC nhảy:
        //
        // 0x802C + 8 = 0x8034
        //
        // Instruction ở 0x8030 phải bị FLUSH.
        // -----------------------------------------------------
        memory[11] = 32'h0034_8463;


        // -----------------------------------------------------
        // 0x0000_8030
        // addi x10, x0, 99
        //
        // PHẢI BỊ FLUSH
        //
        // Nếu cuối simulation:
        //
        // x10 = 99
        //
        // thì flush branch đang sai.
        // -----------------------------------------------------
        memory[12] = 32'h0630_0513;


        // -----------------------------------------------------
        // 0x0000_8034
        // addi x10, x0, 10
        //
        // x10 = 10
        // -----------------------------------------------------
        memory[13] = 32'h00A0_0513;


        // =====================================================
        // JAL TEST
        // =====================================================

        // -----------------------------------------------------
        // 0x0000_8038
        // jal x11, +8
        //
        // rd = PC + 4
        //
        // x11 = 0x0000_803C
        //
        // Target:
        //
        // PC = 0x8038 + 8
        //    = 0x8040
        //
        // Instruction ở 0x803C phải bị FLUSH.
        // -----------------------------------------------------
        memory[14] = 32'h0080_05EF;


        // -----------------------------------------------------
        // 0x0000_803C
        // addi x12, x0, 99
        //
        // PHẢI BỊ FLUSH do JAL
        // -----------------------------------------------------
        memory[15] = 32'h0630_0613;


        // -----------------------------------------------------
        // 0x0000_8040
        // addi x12, x0, 12
        //
        // x12 = 12
        // -----------------------------------------------------
        memory[16] = 32'h00C0_0613;


        // =====================================================
        // END PROGRAM
        // =====================================================

        // -----------------------------------------------------
        // 0x0000_8044
        // beq x0, x0, 0
        //
        // Luôn branch về chính nó.
        //
        // PC = 0x00008044
        //
        // Chương trình dừng ở vòng lặp này.
        // -----------------------------------------------------
        memory[17] = 32'h0000_0063;

    end

endmodule
